param(
  [string]$ManifestPath = "v6_manifest.json",
  [string]$OutputDir = "generated"
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

function Resolve-RepoPath {
  param([string]$PathFromRepoRoot)
  $repoRoot = Resolve-Path (Join-Path $PSScriptRoot "..\..")
  return Join-Path $repoRoot $PathFromRepoRoot
}

function Validate-Manifest {
  param([pscustomobject]$Manifest)

  if ([string]::IsNullOrWhiteSpace($Manifest.schema_version)) { throw "Missing manifest field: schema_version" }
  if ([string]::IsNullOrWhiteSpace($Manifest.project)) { throw "Missing manifest field: project" }
  if ([string]::IsNullOrWhiteSpace($Manifest.firmware_version)) { throw "Missing manifest field: firmware_version" }
  if ([string]::IsNullOrWhiteSpace($Manifest.build_channel)) { throw "Missing manifest field: build_channel" }

  if (-not $Manifest.default_target) { throw "Missing manifest object: default_target" }
  if ([string]::IsNullOrWhiteSpace($Manifest.default_target.hardware_target)) { throw "Missing default_target.hardware_target" }
  if ([string]::IsNullOrWhiteSpace($Manifest.default_target.fermenter_id)) { throw "Missing default_target.fermenter_id" }

  if (-not $Manifest.targets) { throw "Missing manifest array: targets" }
  if ($Manifest.targets.Count -lt 1) { throw "targets must contain at least one entry" }

  foreach ($t in $Manifest.targets) {
    if ([string]::IsNullOrWhiteSpace($t.id)) { throw "Each target must have id" }
    if ([string]::IsNullOrWhiteSpace($t.hardware_target)) { throw "Target '$($t.id)' missing hardware_target" }
    if ([string]::IsNullOrWhiteSpace($t.fermenter_id)) { throw "Target '$($t.id)' missing fermenter_id" }
  }
}

$manifestFullPath = Resolve-RepoPath $ManifestPath
if (-not (Test-Path $manifestFullPath)) {
  throw "Manifest not found: $manifestFullPath"
}

$manifestRaw = Get-Content -Path $manifestFullPath -Raw
$manifest = $manifestRaw | ConvertFrom-Json
Validate-Manifest $manifest

$outputFullDir = Resolve-RepoPath $OutputDir
if (-not (Test-Path $outputFullDir)) {
  New-Item -ItemType Directory -Path $outputFullDir | Out-Null
}

$sha = [System.Security.Cryptography.SHA256]::Create()
try {
  $manifestBytes = [System.Text.Encoding]::UTF8.GetBytes($manifestRaw)
  $hashBytes = $sha.ComputeHash($manifestBytes)
  $manifestHash = ([System.BitConverter]::ToString($hashBytes)).Replace("-", "").ToLowerInvariant()
} finally {
  $sha.Dispose()
}

$targetsJson = $manifest.targets | ConvertTo-Json -Depth 4 -Compress
$escapedTargetsJson = $targetsJson.Replace("\\", "\\\\").Replace('"', '\\"')

$headerLines = @(
  "#pragma once",
  "",
  "// Auto-generated by tools/v6/generate_build_info.ps1",
  "// Do not edit manually.",
  "",
  "#define V6_SCHEMA_VERSION `"$($manifest.schema_version)`"",
  "#define V6_PROJECT_NAME `"$($manifest.project)`"",
  "#define V6_FIRMWARE_VERSION `"$($manifest.firmware_version)`"",
  "#define V6_BUILD_CHANNEL `"$($manifest.build_channel)`"",
  "#define V6_DEFAULT_HARDWARE_TARGET `"$($manifest.default_target.hardware_target)`"",
  "#define V6_DEFAULT_FERMENTER_ID `"$($manifest.default_target.fermenter_id)`"",
  "#define V6_TARGET_COUNT $($manifest.targets.Count)",
  "#define V6_MANIFEST_SHA256 `"$manifestHash`"",
  "",
  "static const char* V6_TARGETS_JSON = `"$escapedTargetsJson`";",
  ""
)
$headerContent = ($headerLines -join "`n")

$generatedInfo = [ordered]@{
  schema_version = $manifest.schema_version
  project = $manifest.project
  firmware_version = $manifest.firmware_version
  build_channel = $manifest.build_channel
  default_target = [ordered]@{
    hardware_target = $manifest.default_target.hardware_target
    fermenter_id = $manifest.default_target.fermenter_id
  }
  target_count = $manifest.targets.Count
  targets = $manifest.targets
  manifest_sha256 = $manifestHash
}
$jsonContent = ($generatedInfo | ConvertTo-Json -Depth 6)

$headerPath = Join-Path $outputFullDir "v6_build_info.h"
$jsonPath = Join-Path $outputFullDir "v6_build_info.json"

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($headerPath, $headerContent + "`n", $utf8NoBom)
[System.IO.File]::WriteAllText($jsonPath, $jsonContent + "`n", $utf8NoBom)

Write-Host "Generated: $headerPath"
Write-Host "Generated: $jsonPath"
